PROMPT 3. COLUMNAS DE RESUMEN_COMPRA_MQ
PROMPT ============================================================

SELECT
    COLUMN_ID,
    COLUMN_NAME,
    DATA_TYPE,
    DATA_LENGTH,
    DATA_PRECISION,
    DATA_SCALE,
    NULLABLE
FROM USER_TAB_COLUMNS
WHERE TABLE_NAME = 'RESUMEN_COMPRA_MQ'
ORDER BY COLUMN_ID;

