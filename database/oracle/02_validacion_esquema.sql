SELECT TABLE_NAME
FROM USER_TABLES
WHERE TABLE_NAME IN (
    'USUARIOS',
    'CURSOS',
    'INSCRIPCIONES',
    'INSCRIPCION_CURSOS',
    'EVALUACIONES',
    'PAGOS',
    'NOTIFICACION',
    'RESUMEN_COMPRA_MQ'
)
ORDER BY TABLE_NAME;

