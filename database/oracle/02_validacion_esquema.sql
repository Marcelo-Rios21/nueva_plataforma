PROMPT ============================================================
PROMPT 4. ULTIMOS RESUMENES CONSUMIDOS DESDE RABBITMQ
PROMPT ============================================================

SELECT *
FROM (
    SELECT
        ID,
        INSCRIPCION_ID,
        ESTUDIANTE_ID,
        NUMERO_RESUMEN,
        TOTAL,
        METODO_PAGO,
        ESTADO_PAGO,
        FECHA_GUARDADO
    FROM RESUMEN_COMPRA_MQ
    ORDER BY FECHA_GUARDADO DESC
)
WHERE ROWNUM <= 20;

